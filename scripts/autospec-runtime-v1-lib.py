def write_json(path: Path, data: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text.rstrip() + "\n", encoding="utf-8")


def yaml_scalar(value) -> str:
    text = str(value)
    if text in {"true", "false"} or re.fullmatch(r"-?\d+(?:\.\d+)?", text):
        return text
    escaped = text.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def load_json(path: Path, default):
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
        return data if isinstance(data, dict) else default
    except Exception:
        return default


def reports(root: Path) -> Path:
    path = root / ".autospec/reports"
    path.mkdir(parents=True, exist_ok=True)
    return path


def state(root: Path) -> Path:
    path = root / ".autospec/state"
    path.mkdir(parents=True, exist_ok=True)
    return path


def slug(value: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", value.lower()).strip("-") or "item"


def package_text(root: Path) -> str:
    path = root / "package.json"
    return path.read_text(encoding="utf-8", errors="ignore").lower() if path.exists() else ""


def stack_profile(root: Path) -> dict:
    data = load_json(state(root) / "stack-profile.json", {})
    if data:
        return data
    from autospec_autonomy_stack import detect_stack

    detect_stack(root)
    return load_json(state(root) / "stack-profile.json", {})


