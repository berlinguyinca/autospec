def load_adapters(root: Path) -> list[dict]:
    data = load_json(state(root) / "runtime-adapters.json", {})
    if not data.get("adapters"):
        runtime_adapter_index(root)
        data = load_json(state(root) / "runtime-adapters.json", {})
    return data.get("adapters", [])


def load_features(root: Path) -> list[dict]:
    data = load_json(state(root) / "feature-slices.json", {})
    if not data.get("feature_slices"):
        feature_slice_index(root)
        data = load_json(state(root) / "feature-slices.json", {})
    return data.get("feature_slices", [])


def selected_feature(root: Path, feature_id: str) -> dict:
    features = load_features(root)
    return next((item for item in features if item["id"] == feature_id), features[0])


def selected_adapter(root: Path, feature_id: str) -> dict | None:
    candidates = [item for item in load_adapters(root) if item.get("match_status") == "available" and feature_id in item.get("supported_feature_slices", [])]
    if not candidates:
        return None
    return max(candidates, key=lambda item: len(item["detection"].get("required_files", [])))


def file_plan_for(root: Path, adapter_item: dict | None, feature_item: dict) -> tuple[list[str], list[str], list[str]]:
    fid = feature_item["id"]
    component, route = feature_item["generated_artifacts"][0], feature_item["generated_artifacts"][1]
    docs = [f"docs/specs/{fid}.md"]
    tests = [f"tests/e2e/autospec-{fid}.spec.ts"] if "@playwright/test" in package_text(root) else []
    if not adapter_item:
        return docs, [], []
    aid = adapter_item["id"]
    if aid == "react-vite":
        return [f"src/components/autospec/{component}.tsx", f"src/pages/{route}.tsx", *docs], [], tests
    if aid == "nextjs-app-router":
        return [f"src/components/autospec/{component}.tsx", f"app/{slug(route)}/page.tsx", *docs], [], tests
    if aid == "nextjs-pages-router":
        return [f"src/components/autospec/{component}.tsx", f"pages/{slug(route)}.tsx", *docs], [], tests
    return docs, [], tests


def runtime_plan(root: Path, feature_id: str = "", issue: str = "", rule_id: str = "") -> int:
    profile = stack_profile(root).get("primary_profile", {})
    if not feature_id:
        feature_id = "in-app-docs-center"
    feature_item = selected_feature(root, feature_id)
    adapter_item = selected_adapter(root, feature_id)
    confidence = float(profile.get("confidence", 0) or 0)
    files, updates, tests = file_plan_for(root, adapter_item, feature_item)
    status = "safe_to_generate"
    reason = "recognized stack and adapter support this feature slice"
    if confidence < 0.8:
        status, reason = "low_stack_confidence", "stack confidence is below 0.8"
    elif not adapter_item:
        status, reason = "missing_adapter", "no adapter supports this feature for the detected stack"
    elif feature_item["runtime_claim_level"] == "shell":
        status = "safe_to_generate"
    payload = {
        "schema": 1,
        "plans": [{
            "feature_slice_id": feature_item["id"],
            "source_rule_ids": feature_item["source_rules"],
            "adapter": adapter_item["id"] if adapter_item else "",
            "stack_confidence": confidence,
            "files_to_create": files,
            "files_to_update": updates,
            "tests_to_create": tests,
            "metadata_to_update": feature_item["metadata_updates"],
            "expected_validation": ["bash scripts/autospec-verify-runtime-feature.sh --dry-run"],
            "runtime_claim_level": feature_item["runtime_claim_level"],
            "risk": feature_item["risk_level"],
            "status": status,
            "reason": reason,
            "next_command": f"bash scripts/autospec-generate-runtime-feature.sh --dry-run --feature {feature_item['id']}",
        }]
    }
    write_json(state(root) / "runtime-implementation-plan.json", payload)
    write_json(reports(root) / "runtime-implementation-plan.json", payload)
    write_text(reports(root) / "runtime-implementation-plan.md", "\n".join([
        "# Runtime Implementation Plan",
        "",
        "## Summary",
        "",
        f"- Feature: `{feature_item['id']}`",
        f"- Status: `{status}`",
        f"- Adapter: `{adapter_item['id'] if adapter_item else 'none'}`",
        f"- Runtime claim level: `{feature_item['runtime_claim_level']}`",
        "",
        "## Expected files",
        "",
        "\n".join(f"- `{p}`" for p in files) or "- None.",
    ]))
    return 0


def generated_header(feature_id: str, claim: str, ext: str) -> str:
    text = f"{HEADER}\nFeature slice: {feature_id}.\nRuntime claim level: {claim}.\nReview before production use."
    return "\n".join(f"// {line}" for line in text.splitlines()) + "\n" if ext in {".tsx", ".ts", ".js"} else "<!-- " + text.replace("\n", " ") + " -->\n"


def component_body(feature_item: dict) -> str:
    fid = feature_item["id"]
    title = feature_item["title"]
    body_by_feature = {
        "ai-provider-settings": "OpenAI OpenAI-compatible Ollama base URL model embedding model RAG enabled token/cost tracking test connection placeholder secret references only",
        "ai-usage-token-dashboard": "prompt tokens completion tokens total tokens estimated cost requests user project model provider date chart placeholder export placeholder",
        "rag-assistant-shell": "chat UI citation/source area no-context fallback loading state error state docs/RAG source panel no model calls",
        "capability-interface-shell": "detected capabilities natural-language action mapping placeholder permission notes explainability area",
        "pretty-rendering-viewers": "JSON tree YAML code SQL viewer Markdown renderer table chart placeholder raw JSON avoidance policy",
        "analytics-dashboard-shell": "summary cards chart placeholder table placeholder filters empty loading error states chart selection policy",
    }
    body = body_by_feature.get(fid, "responsive shell empty state loading state error state accessibility notes keyboard focus notes")
    return f"export function {feature_item['generated_artifacts'][0]}() {{\n  return <main aria-label=\"{title}\"><h1>{title}</h1><p>{body}</p></main>;\n}}\n"


def route_body(feature_item: dict, route_rel: str) -> str:
    component = feature_item["generated_artifacts"][0]
    component_module = f"src/components/autospec/{component}"
    route_dir = Path(route_rel).parent.as_posix()
    import_path = os.path.relpath(component_module, route_dir).replace(os.sep, "/")
    if not import_path.startswith("."):
        import_path = f"./{import_path}"
    return f"import {{ {component} }} from '{import_path}';\n\nexport default function {feature_item['generated_artifacts'][1]}Page() {{\n  return <{component} />;\n}}\n"


def safe_write(root: Path, rel: str, text: str, confirm: bool) -> tuple[bool, str]:
    path = root / rel
    if any(rel.startswith(forbidden.rstrip("*")) for forbidden in [".github/workflows", ".env", "migrations/"]):
        return False, "forbidden path"
    if path.exists() and HEADER not in path.read_text(encoding="utf-8", errors="ignore"):
        return False, "unsafe overwrite blocked"
    if confirm:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    return True, ""


def generate_runtime(root: Path, feature_id: str, issue: str = "", confirm: bool = False) -> int:
    runtime_plan(root, feature_id, issue)
    plan = load_json(state(root) / "runtime-implementation-plan.json", {"plans": []}).get("plans", [{}])[0]
    feature_item = selected_feature(root, plan.get("feature_slice_id") or feature_id)
    status = plan.get("status")
    if status not in {"safe_to_generate", "safe_shell_only"}:
        result = {"schema": 1, "feature_id": feature_item["id"], "status": status, "reason": plan.get("reason", ""), "side_effects": {"wrote_files": False}}
        write_json(reports(root) / "runtime-generation-result.json", result)
        write_text(reports(root) / "runtime-generation-result.md", f"# Runtime Generation Result\n\n## Summary\n\nBlocked: `{status}`")
        return 1
    created = []
    errors = []
    for rel in plan.get("files_to_create", []):
        suffix = Path(rel).suffix
        if rel.endswith(".tsx"):
            text = generated_header(feature_item["id"], feature_item["runtime_claim_level"], suffix)
            text += component_body(feature_item) if "/components/" in rel else route_body(feature_item, rel)
        else:
            extra = "\nNo database migration. No auth/security behavior change. No dependency installation.\n" if feature_item["id"] == "ai-usage-token-dashboard" else "\nShell/partial runtime slice; review before production use.\n"
            text = generated_header(feature_item["id"], feature_item["runtime_claim_level"], suffix) + f"# {feature_item['title']}\n{extra}"
        ok, err = safe_write(root, rel, text, confirm)
        if ok:
            created.append(rel)
        else:
            errors.append(f"{rel}: {err}")
    if feature_item["id"] in {"ai-usage-token-dashboard", "analytics-dashboard-shell", "pretty-rendering-viewers"}:
        dep = root / ".autospec/backlog/runtime-dependencies" / f"{feature_item['id']}.md"
        if confirm:
            write_text(dep, f"# Dependency decision for {feature_item['title']}\n\nNo dependencies were installed automatically. Decide chart/viewer/data dependencies through ADR first.\n")
    record = {
        "schema": 1,
        "feature_id": feature_item["id"],
        "adapter": plan.get("adapter"),
        "runtime_claim_level": feature_item["runtime_claim_level"],
        "status": "generated" if confirm else "planned",
        "generated_files": created,
        "metadata_updates": plan.get("metadata_to_update", []),
        "tests_to_create": plan.get("tests_to_create", []),
        "errors": errors,
        "side_effects": {"wrote_files": confirm},
    }
    write_json(reports(root) / "runtime-generation-plan.json", {"schema": 1, "plan": plan})
    write_text(reports(root) / "runtime-generation-plan.md", f"# Runtime Generation Plan\n\n## Summary\n\n- Feature: `{feature_item['id']}`\n- Runtime claim level: `{feature_item['runtime_claim_level']}`")
    write_json(reports(root) / "runtime-generation-result.json", record)
    write_text(reports(root) / "runtime-generation-result.md", f"# Runtime Generation Result\n\n## Summary\n\nStatus: `{record['status']}`\n\n## Runtime claim level\n\n`{feature_item['runtime_claim_level']}`")
    write_json(state(root) / "runtime-generations" / f"{feature_item['id']}.json", record)
    write_text(state(root) / "runtime-generations" / f"{feature_item['id']}.md", f"# Runtime Generation: {feature_item['id']}\n\nStatus: `{record['status']}`")
    return 0 if not errors else 1


def playwright_generation(root: Path, feature_id: str = "", confirm: bool = False) -> int:
    feature_id = feature_id or "in-app-docs-center"
    has_pw = "@playwright/test" in package_text(root)
    output = f"tests/e2e/autospec-{feature_id}.spec.ts"
    if has_pw and confirm:
        write_text(root / output, "\n".join([
            "// Generated by Autospec runtime feature generator.",
            f"// Feature slice: {feature_id}.",
            "import { test, expect } from '@playwright/test';",
            "test.describe('Autospec runtime evidence', () => {",
            "  for (const viewport of [{ width: 320, height: 640 }, { width: 768, height: 1024 }, { width: 1440, height: 900 }]) {",
            "    test(`renders without white-screen at ${viewport.width}x${viewport.height}`, async ({ page }) => {",
            "      await page.setViewportSize(viewport);",
            "      await page.goto('/');",
            "      await expect(page.locator('body')).toBeVisible();",
            "    });",
            "  }",
            "});",
        ]))
    if not has_pw:
        issue = root / ".autospec/backlog/runtime-dependencies" / "playwright-adoption.md"
        write_text(issue, "# Playwright adoption decision\n\nPlaywright is missing; Autospec did not install it automatically.\n")
    payload = {"schema": 1, "feature_id": feature_id, "playwright_detected": has_pw, "output": output if has_pw else "", "side_effects": {"wrote_file": bool(has_pw and confirm)}}
    write_json(reports(root) / "playwright-generation-plan.json", payload)
    write_text(reports(root) / "playwright-generation-plan.md", "# Playwright Generation Plan\n\n## Summary\n\n" + ("Generate viewport/white-screen evidence tests." if has_pw else "Playwright missing; adoption spec generated."))
    write_json(reports(root) / "playwright-generation-result.json", payload)
    write_text(reports(root) / "playwright-generation-result.md", "# Playwright Generation Result\n\n## Summary\n\nDone.")
    return 0


