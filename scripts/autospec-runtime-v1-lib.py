def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--repo-root", default=".")
    parser.add_argument("--command", required=True)
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--confirm", action="store_true")
    parser.add_argument("--feature", default="")
    parser.add_argument("--issue", default="")
    parser.add_argument("--rule", default="")
    args = parser.parse_args()
    root = Path(args.repo_root).resolve()
    handlers = {
        "adapter-index": lambda: runtime_adapter_index(root),
        "feature-slice-index": lambda: feature_slice_index(root),
        "runtime-plan": lambda: runtime_plan(root, args.feature, args.issue, args.rule),
        "generate-runtime": lambda: generate_runtime(root, args.feature or "in-app-docs-center", args.issue, args.confirm),
        "playwright-generation": lambda: playwright_generation(root, args.feature, args.confirm),
        "metadata-sync": lambda: sync_runtime_metadata(root, args.confirm),
        "verify-runtime": lambda: verify_runtime(root, args.feature, args.issue),
        "worker-runtime": lambda: worker_runtime(root, args.feature or "in-app-docs-center", args.issue or "1", args.confirm),
        "status": lambda: runtime_status(root),
    }
    if args.command not in handlers:
        raise SystemExit(f"unknown command: {args.command}")
    return handlers[args.command]()


if __name__ == "__main__":
    raise SystemExit(main())
