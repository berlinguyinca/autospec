def write_adapter_files(root: Path, adapters: list[dict]) -> None:
    base = root / ".autospec/adapters"
    write_text(base / "README.md", "# Runtime Adapters\n\nAdapters define safe file-generation patterns for recognized target stacks.\n")
    for item in adapters:
        lines = [
            f"id: {yaml_scalar(item['id'])}",
            f"title: {yaml_scalar(item['title'])}",
            "stack_profiles:",
            *[f"  - {yaml_scalar(p)}" for p in item["stack_profiles"]],
            f"status: {yaml_scalar(item['status'])}",
            f"confidence_required: {item['confidence_required']}",
            "supported_feature_slices:",
            *[f"  - {yaml_scalar(f)}" for f in item["supported_feature_slices"]],
            "allowed_paths:",
            *[f"  - {yaml_scalar(p)}" for p in item["allowed_paths"]],
            "forbidden_paths:",
            *[f"  - {yaml_scalar(p)}" for p in item["forbidden_paths"]],
            "validation:",
            "  focused_commands:",
            *[f"    - {yaml_scalar(c)}" for c in item["validation"]["focused_commands"]],
            "risk:",
            f"  default_level: {yaml_scalar(item['risk']['default_level'])}",
            f"  requires_human_guidance: {str(item['risk']['requires_human_guidance']).lower()}",
        ]
        write_text(base / f"{item['id']}.yml", "\n".join(lines))


def runtime_adapter_index(root: Path) -> int:
    profile = stack_profile(root).get("primary_profile", {})
    adapters = built_in_adapters()
    for item in adapters:
        required = item["detection"].get("required_files", [])
        required_ok = all((root / rel).exists() for rel in required)
        stack_ok = profile.get("id") in item["stack_profiles"] and float(profile.get("confidence", 0) or 0) >= item["confidence_required"]
        item["match_status"] = "available" if stack_ok and required_ok else "unsupported"
        item["match_reason"] = "stack profile and required files match" if item["match_status"] == "available" else "stack profile, confidence, or route convention did not match"
    payload = {"schema": 1, "detected_stack": profile, "adapters": adapters}
    write_adapter_files(root, adapters)
    write_json(state(root) / "runtime-adapters.json", payload)
    write_json(reports(root) / "runtime-adapters.json", payload)
    write_text(reports(root) / "runtime-adapters.md", "\n".join([
        "# Runtime Adapters",
        "",
        "## Summary",
        "",
        f"- Detected stack: `{profile.get('id', 'unknown')}`",
        "",
        "| Adapter | Status | Feature slices |",
        "| --- | --- | ---: |",
        "\n".join(f"| `{a['id']}` | {a['match_status']} | {len(a['supported_feature_slices'])} |" for a in adapters),
    ]))
    return 0


