def verify_runtime(root: Path, feature_id: str = "", issue: str = "") -> int:
    feature_id = feature_id or load_json(reports(root) / "runtime-generation-result.json", {}).get("feature_id", "")
    record = load_json(state(root) / "runtime-generations" / f"{feature_id}.json", load_json(reports(root) / "runtime-generation-result.json", {}))
    findings = []
    if not record:
        findings.append("runtime-generation report missing")
    for rel in record.get("generated_files", []):
        path = root / rel
        if not path.exists() and record.get("status") == "generated":
            findings.append(f"generated file missing: {rel}")
        if path.exists():
            text = path.read_text(encoding="utf-8", errors="ignore")
            if "API_KEY" in text or "password=" in text.lower():
                findings.append(f"secret-like content exposed: {rel}")
            if record.get("runtime_claim_level") == "shell" and re.search(r"fully implemented|real model call|db persistence", text, re.I):
                findings.append(f"runtime claim overstated: {rel}")
    metadata = load_json(state(root) / "ui-surface.json", {})
    if record.get("status") == "generated" and not metadata:
        findings.append("metadata sync missing")
    verdict = "pass" if not findings else "warn"
    payload = {"schema": 1, "feature_id": feature_id, "verdict": verdict, "findings": findings, "runtime_claim_honesty": "checked", "side_effects": {"github_writes": False}}
    write_json(reports(root) / "runtime-feature-verification.json", payload)
    write_text(reports(root) / "runtime-feature-verification.md", "\n".join([
        "# Runtime Feature Verification",
        "",
        "## Summary",
        "",
        f"- Verdict: `{verdict}`",
        "",
        "## Runtime Claim Honesty",
        "",
        "- Shell/partial/complete wording checked.",
        "",
        "## Findings",
        "",
        "\n".join(f"- {f}" for f in findings) or "- None.",
    ]))
    return 0 if verdict in {"pass", "warn"} else 1


def worker_runtime(root: Path, feature_id: str, issue: str, confirm: bool) -> int:
    runtime_adapter_index(root)
    feature_slice_index(root)
    runtime_plan(root, feature_id, issue)
    code = generate_runtime(root, feature_id, issue, confirm)
    if code == 0:
        playwright_generation(root, feature_id, confirm)
        sync_runtime_metadata(root, confirm)
        verify_runtime(root, feature_id, issue)
    result = load_json(reports(root) / "runtime-generation-result.json", {})
    md = "\n".join([
        "# Runtime Feature Generation",
        "",
        "## Summary",
        "",
        f"- Feature: `{feature_id}`",
        f"- Status: `{result.get('status', 'unknown')}`",
        f"- Runtime claim level: `{result.get('runtime_claim_level', 'unknown')}`",
        "",
        "## Source issue",
        "",
        f"`{issue}`",
        "",
        "## Constitution/baseline references",
        "",
        "- Constitution rule context: runtime feature slice.",
        "- Baseline: target-app runtime shell.",
        "",
        "## Safety notes",
        "",
        "- No GitHub writes, migrations, auth/security changes, dependency upgrades, scheduler, merge, or approval.",
    ])
    write_text(reports(root) / "worker-runtime-feature-result.md", md)
    write_text(reports(root) / "worker-pr-body.md", md)
    if code == 0:
        evidence_helper = Path(__file__).with_name("autospec-evidence-v1-lib.py")
        if evidence_helper.exists():
            subprocess.run(
                [
                    sys.executable,
                    str(evidence_helper),
                    "--repo-root",
                    str(root),
                    "--command",
                    "worker-evidence",
                    "--issue",
                    issue,
                    "--feature",
                    feature_id,
                ],
                cwd=str(root),
                check=False,
                text=True,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
            )
    return code


