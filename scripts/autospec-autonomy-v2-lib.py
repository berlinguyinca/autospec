def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--repo-root", default=".")
    parser.add_argument("--command", required=True)
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--confirm", action="store_true")
    parser.add_argument("--rule", default="")
    parser.add_argument("--issue", default="1")
    parser.add_argument("--recipe", default="")
    parser.add_argument("--template", default="")
    parser.add_argument("--output", default="")
    parser.add_argument("--allow-overwrite", action="store_true")
    parser.add_argument("--auto-recipe", action="store_true")
    parser.add_argument("--capability", default="")
    parser.add_argument("--var", action="append", default=[])
    args = parser.parse_args()
    root = Path(args.repo_root).resolve()
    handlers = {
        "recipe-index": lambda: recipe_index(root),
        "detect-stack": lambda: detect_stack(root),
        "rule-to-recipe": lambda: rule_to_recipe(root, args.rule),
        "decompose": lambda: decompose(root, args.recipe),
        "patch-plan": lambda: patch_plan(root, args.recipe, args.issue),
        "apply-template": lambda: apply_template(root, args.template, args.output, args.confirm, dict(v.split("=", 1) for v in args.var), args.allow_overwrite),
        "worker-recipe": lambda: worker_recipe(root, args.recipe, args.issue, args.confirm, args.auto_recipe),
        "evidence-tests": lambda: evidence_tests(root, args.capability, args.confirm),
        "rule-recheck": lambda: rule_recheck(root, args.rule, args.issue),
        "status": lambda: autonomy_status(root),
    }
    if args.command not in handlers:
        raise SystemExit(f"unknown command: {args.command}")
    return handlers[args.command]()


if __name__ == "__main__":
    raise SystemExit(main())
