def rule_recheck(root: Path, rule_filter: str = "", issue: str = "1") -> int:
    rows = []
    for rule in rule_results(root):
        if rule_filter and rule.get("rule_id") != rule_filter:
            continue
        rows.append({"rule_id": rule.get("rule_id"), "before_status": rule.get("status", "unknown"), "after_status": rule.get("status", "unknown"), "evidence": rule.get("evidence", []), "skip_rationale": "No metadata-changing confirmed work detected; status preserved."})
    payload = {"schema": 1, "issue": issue, "results": rows, "changed": False}
    write_json(reports(root) / "rule-recheck.json", payload)
    wid = state(root) / "work-items" / str(issue)
    write_json(wid / "rule-recheck.json", payload)
    md = "# Rule Recheck\n\n## Summary\n\n" + "\n".join(f"- `{r['rule_id']}`: {r['before_status']} -> {r['after_status']}" for r in rows)
    write_text(reports(root) / "rule-recheck.md", md)
    write_text(wid / "rule-recheck.md", md)
    return 0


