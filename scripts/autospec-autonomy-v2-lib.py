def write_json(path: Path, data: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text.rstrip() + "\n", encoding="utf-8")


def yaml_scalar(value) -> str:
    text = str(value)
    if text in {"true", "false", "[]"} or re.fullmatch(r"-?\d+(?:\.\d+)?", text):
        return text
    escaped = text.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def load_json(path: Path, default):
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
        return data if isinstance(data, dict) else default
    except Exception:
        return default


def reports(root: Path) -> Path:
    path = root / ".autospec/reports"
    path.mkdir(parents=True, exist_ok=True)
    return path


def state(root: Path) -> Path:
    path = root / ".autospec/state"
    path.mkdir(parents=True, exist_ok=True)
    return path


def slug(value: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", value.lower()).strip("-") or "item"


def default_capabilities() -> list[dict]:
    enabled = {"docs", "specs", "metadata", "tests", "cli", "scripts", "playwright_scaffold", "ai_scaffold", "nlai_scaffold", "diagnostics_scaffold", "reporting_scaffold", "security_privacy_docs", "dependency_planning", "modernization_planning"}
    experimental = {"ui_scaffold", "api_scaffold", "settings_scaffold"}
    rows = []
    for cap in CAPABILITY_IDS:
        status = "enabled" if cap in enabled else "experimental" if cap in experimental else "planned"
        risk = "medium" if cap in experimental else "low"
        title = cap.replace("_", " ").title()
        if cap == "playwright_scaffold":
            title = "Playwright scaffolds"
        rows.append({
            "id": cap,
            "title": title,
            "status": status,
            "risk_level": risk,
            "allowed_by_default": cap in enabled,
            "allowed_paths": ["docs/**", ".autospec/**", "tests/**"] + (["src/**"] if cap in experimental else []),
            "forbidden_paths": FORBIDDEN_PATHS,
            "max_files_changed": 5 if cap in enabled else 3,
            "max_lines_changed": 250 if cap in enabled else 120,
            "requires_tests": cap in {"tests", "playwright_scaffold", "ui_scaffold", "api_scaffold", "settings_scaffold"},
            "requires_verifier": True,
            "requires_human_guidance": cap in {"api_scaffold", "settings_scaffold"} if cap in experimental else False,
            "requires_architecture_review": cap in {"api_scaffold", "settings_scaffold"},
            "can_modify_code": cap in {"cli", "scripts", "tests", "playwright_scaffold", "ui_scaffold", "api_scaffold", "settings_scaffold"},
            "can_modify_dependencies": False,
            "can_modify_database": False,
            "can_modify_auth_security": False,
            "supported_repo_types": ["web", "cli", "internal-tool"],
            "supported_technologies": [],
            "input_requirements": ["structured rule or explicit operator request"],
            "output_artifacts": [".autospec/reports", ".autospec/state"],
            "validation_expectations": ["focused validation or honest skip rationale"],
            "fallback_when_unsafe": "stuck/guidance",
        })
    return rows


def capability_yaml(rows: list[dict]) -> str:
    lines = ["schema: 1", "capabilities:"]
    for row in rows:
        lines.extend([
            f"- id: {row['id']}",
            f"  title: {row['title']}",
            f"  status: {row['status']}",
            f"  risk_level: {row['risk_level']}",
            f"  allowed_by_default: {str(row['allowed_by_default']).lower()}",
            "  allowed_paths:",
            *[f"    - {yaml_scalar(p)}" for p in row["allowed_paths"]],
            "  forbidden_paths:",
            *[f"    - {yaml_scalar(p)}" for p in row["forbidden_paths"]],
            f"  max_files_changed: {row['max_files_changed']}",
            f"  max_lines_changed: {row['max_lines_changed']}",
            f"  requires_tests: {str(row['requires_tests']).lower()}",
            "  requires_verifier: true",
            f"  requires_human_guidance: {str(row['requires_human_guidance']).lower()}",
            f"  requires_architecture_review: {str(row['requires_architecture_review']).lower()}",
            f"  can_modify_code: {str(row['can_modify_code']).lower()}",
            "  can_modify_dependencies: false",
            "  can_modify_database: false",
            "  can_modify_auth_security: false",
            "  supported_repo_types: []",
            "  supported_technologies: []",
            "  input_requirements:",
            "    - structured rule or explicit operator request",
            "  output_artifacts:",
            "    - .autospec/reports",
            "  validation_expectations:",
            "    - focused validation or honest skip rationale",
            "  fallback_when_unsafe: stuck/guidance",
        ])
    return "\n".join(lines) + "\n"


def load_capability_statuses(root: Path) -> dict[str, str]:
    path = state(root) / "worker-capabilities.yml"
    if not path.exists():
        ensure_capabilities(root)
    statuses = {}
    current = None
    for line in path.read_text(encoding="utf-8", errors="ignore").splitlines():
        m = re.match(r"- id:\s*(\S+)", line)
        if m:
            current = m.group(1)
        m = re.match(r"\s+status:\s*(\S+)", line)
        if m and current:
            statuses[current] = m.group(1)
    return statuses


def ensure_capabilities(root: Path) -> list[dict]:
    rows = default_capabilities()
    write_text(state(root) / "worker-capabilities.yml", capability_yaml(rows))
    write_json(state(root) / "worker-capabilities.json", {"schema": 1, "capabilities": rows})
    write_text(reports(root) / "worker-capabilities.md", "\n".join([
        "# Worker Capabilities",
        "",
        "## Summary",
        "",
        f"- Capabilities: {len(rows)}",
        "",
        "| Capability | Status | Risk | Code |",
        "| --- | --- | --- | --- |",
        "\n".join(f"| `{r['id']}` | {r['status']} | {r['risk_level']} | {r['can_modify_code']} |" for r in rows),
    ]))
    return rows


