// api-reference.mjs — generate API_REFERENCE.md from cluster output.
//
// Exports:
//   generate({ clusters, specs, existingDocs }): GeneratorResult
//
// Output: per-public-export entry with name/signature/source line; scope per file.

import path from 'node:path';
import fs from 'node:fs';

/**
 * Build a scope block for a section.
 */
function scopeBlock(srcGlobs, reason) {
  const srcList = srcGlobs.map(g => `"${g}"`).join(', ');
  return [
    '<!-- autospec-doc-scope:',
    `  src: [${srcList}]`,
    reason ? `  reason: "${reason.replace(/"/g, "'")}"` : '',
    '  generated: true',
    '-->',
  ].filter(l => l !== '').join('\n');
}

/**
 * Extract a leading comment for an export by reading file lines.
 * Returns the first JSDoc or # comment block immediately above the export line.
 * @param {string} filePath
 * @param {number} line  1-indexed
 * @returns {string}
 */
function extractLeadingComment(filePath, line) {
  try {
    const src = fs.readFileSync(filePath, 'utf8').split('\n');
    const target = line - 1; // 0-indexed
    const commentLines = [];

    // Walk backwards from the line above the export
    let i = target - 1;
    // Skip blank lines immediately above
    while (i >= 0 && src[i].trim() === '') i--;

    if (i < 0) return '';

    const topLine = src[i].trim();

    if (topLine === '*/') {
      // JSDoc block: walk up to opening /**
      while (i >= 0 && !src[i].trim().startsWith('/**')) {
        commentLines.unshift(src[i].trim().replace(/^\*\s?/, ''));
        i--;
      }
      if (i >= 0) commentLines.unshift(src[i].trim().replace(/^\/\*\*\s?/, ''));
      return commentLines
        .filter(l => !l.startsWith('*') || l !== '*')
        .map(l => l.replace(/^\*\s?/, '').replace(/\*\/$/, '').trim())
        .filter(Boolean)
        .join(' ');
    }

    if (topLine.startsWith('#') || topLine.startsWith('//')) {
      // Single-line comment
      return topLine.replace(/^[#\/]+\s*/, '');
    }

    return '';
  } catch {
    return '';
  }
}

/**
 * Generate API_REFERENCE.md content.
 */
export function generate({ clusters, specs = [], existingDocs = {} }) {
  const significant = clusters?.significant || [];

  const section_anchors = [];
  const lines = [
    '# API Reference',
    '',
    '> *Auto-generated by autospec reverse-engineer pipeline.*',
    '> *Per-symbol reference for all public exports.*',
    '',
  ];

  if (significant.length === 0) {
    lines.push('> *No public exports detected.*', '');
    return { path: 'docs/API_REFERENCE.md', content: lines.join('\n'), section_anchors };
  }

  for (const unit of significant) {
    if (!unit.exports || unit.exports.length === 0) continue;

    const moduleHeading = `## Module: \`${unit.slug}\``;
    section_anchors.push(moduleHeading);
    const srcGlobs = unit.files.map(f => path.basename(f));

    lines.push(
      moduleHeading,
      '',
      scopeBlock(srcGlobs, `Public API for module ${unit.slug}`),
      '',
      `**Language:** ${unit.language}`,
      `**Files:** ${unit.files.map(f => `\`${path.basename(f)}\``).join(', ')}`,
      '',
    );

    for (const exp of unit.exports) {
      const expHeading = `### \`${exp.name}\` _(${exp.kind})_`;
      section_anchors.push(expHeading);

      // Try to extract leading comment from source file
      const sourceFile = unit.files.find(f => {
        try { fs.accessSync(f); return true; } catch { return false; }
      });
      const comment = sourceFile ? extractLeadingComment(sourceFile, exp.line) : '';

      lines.push(expHeading, '');
      if (comment) lines.push(`> ${comment}`, '');

      if (exp.signature) {
        lines.push(
          '**Signature:**',
          '',
          '```',
          exp.signature,
          '```',
          '',
        );
      }

      lines.push(
        `**Source:** line ${exp.line}`,
        '',
      );
    }
  }

  return {
    path: 'docs/API_REFERENCE.md',
    content: lines.join('\n'),
    section_anchors,
  };
}
