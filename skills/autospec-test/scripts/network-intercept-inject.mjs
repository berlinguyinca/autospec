#!/usr/bin/env node
// network-intercept-inject.mjs — Layer B: inject Playwright network intercept.
//
// Usage: node network-intercept-inject.mjs <repo_root> <contract_json_file>
//
// Writes `playwright/global-setup-autospec.ts` in the target repo.
// Idempotently patches `playwright.config.*` to reference the global setup.
//
// The injected global setup installs a Playwright context.route() handler
// that aborts requests matching any forbidden_url_pattern (post-redirect).
//
// Exit codes: 0=ok, 1=fatal, 2=patterns empty (fail-closed)

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'fs';
import { join, resolve } from 'path';
import { createHash } from 'crypto';

const [,, repoRoot, contractArg] = process.argv;

if (!repoRoot || !contractArg) {
  process.stderr.write('Usage: network-intercept-inject.mjs <repo_root> <contract_json_file>\n');
  process.exit(1);
}

const absRoot = resolve(repoRoot);
if (!existsSync(absRoot)) {
  process.stderr.write(`network-intercept-inject: fatal: repo_root not found: ${repoRoot}\n`);
  process.exit(1);
}

let contract;
try {
  contract = JSON.parse(readFileSync(contractArg, 'utf8'));
} catch (e) {
  process.stderr.write(`network-intercept-inject: fatal: cannot parse contract: ${e.message}\n`);
  process.exit(1);
}

const forbiddenPatterns = contract?.e2e?.forbidden_url_patterns || [];
const intentionallyEmpty = contract?.e2e?.forbidden_url_patterns_intentionally_empty === true;

if (forbiddenPatterns.length === 0 && !intentionallyEmpty) {
  process.stderr.write('network-intercept-inject: refuse-to-run: forbidden_url_patterns is empty without ack\n');
  process.exit(2);
}

// ── Generate global setup content ─────────────────────────────────────────────
const patternsJSON = JSON.stringify(forbiddenPatterns, null, 2);
const AUTOSPEC_MARKER = '// autospec-network-intercept-v1';

const globalSetupContent = `${AUTOSPEC_MARKER}
// Auto-generated by autospec-test network-intercept-inject.mjs
// DO NOT EDIT MANUALLY — re-run autospec-test to regenerate.
import { chromium, FullConfig } from '@playwright/test';

const FORBIDDEN_PATTERNS: RegExp[] = ${patternsJSON}.map(
  (p: string) => new RegExp(p)
);

async function globalSetup(config: FullConfig): Promise<void> {
  if (FORBIDDEN_PATTERNS.length === 0) return;

  // Install network intercept on every browser context via global fixture.
  // This is a pre-test hook — actual per-context intercept is injected by
  // the Playwright fixture in playwright-fixtures/touched.ts.
  // Here we validate that the base URLs are not forbidden (Layer A defense-in-depth).
  const baseURL = config.projects?.[0]?.use?.baseURL
    || config.use?.baseURL
    || '';
  for (const pattern of FORBIDDEN_PATTERNS) {
    if (pattern.test(baseURL)) {
      console.error(\`[autospec] FATAL: baseURL "\${baseURL}" matches forbidden pattern \${pattern}\`);
      process.exit(2);
    }
  }
}

export default globalSetup;
`;

// ── Write global setup file ────────────────────────────────────────────────────
const playwrightDir = join(absRoot, 'playwright');
mkdirSync(playwrightDir, { recursive: true });
const globalSetupPath = join(playwrightDir, 'global-setup-autospec.ts');

// Idempotency: check if content has changed
let needsWrite = true;
if (existsSync(globalSetupPath)) {
  const existing = readFileSync(globalSetupPath, 'utf8');
  const existingHash = createHash('sha256').update(existing).digest('hex');
  const newHash = createHash('sha256').update(globalSetupContent).digest('hex');
  needsWrite = existingHash !== newHash;
}

if (needsWrite) {
  writeFileSync(globalSetupPath, globalSetupContent, 'utf8');
  process.stderr.write(`network-intercept-inject: wrote ${globalSetupPath}\n`);
} else {
  process.stderr.write(`network-intercept-inject: global-setup-autospec.ts unchanged (idempotent)\n`);
}

// ── Idempotently patch playwright.config.* ────────────────────────────────────
const CONFIG_EXTS = ['ts', 'js', 'mjs', 'cjs'];
let configPath = null;

for (const ext of CONFIG_EXTS) {
  const candidate = join(absRoot, `playwright.config.${ext}`);
  if (existsSync(candidate)) {
    configPath = candidate;
    break;
  }
}

const GLOBAL_SETUP_REF = "globalSetup: './playwright/global-setup-autospec'";
const GLOBAL_SETUP_MARKER = '// autospec: globalSetup injected';

if (configPath) {
  let configContent = readFileSync(configPath, 'utf8');
  if (!configContent.includes('global-setup-autospec')) {
    // Find a good insertion point — after the opening defineConfig({ or module.exports = {
    const insertMarker = configContent.match(/defineConfig\s*\(\s*\{|module\.exports\s*=\s*\{/);
    if (insertMarker) {
      const insertPos = insertMarker.index + insertMarker[0].length;
      configContent = configContent.slice(0, insertPos) +
        `\n  ${GLOBAL_SETUP_REF}, ${GLOBAL_SETUP_MARKER}` +
        configContent.slice(insertPos);
      writeFileSync(configPath, configContent, 'utf8');
      process.stderr.write(`network-intercept-inject: patched ${configPath}\n`);
    }
  } else {
    process.stderr.write(`network-intercept-inject: ${configPath} already references global-setup-autospec (idempotent)\n`);
  }
}

const result = {
  globalSetupPath: globalSetupPath.replace(absRoot + '/', ''),
  configPatched: configPath ? configPath.replace(absRoot + '/', '') : null,
  idempotent: !needsWrite,
  patternsCount: forbiddenPatterns.length,
};

process.stdout.write(JSON.stringify(result, null, 2) + '\n');
process.exit(0);
