#!/usr/bin/env node
// findings-generator.mjs — LLM findings generator for autospec-test.
//
// Usage: node findings-generator.mjs <gate_result_json_file> <repo_root>
//
// Non-blocking, idempotent: writes .autospec/test-findings.md in the target repo.
// Content-hash gated: if inputs haven't changed, existing file is preserved.
//
// Uses Codex CLI or gh CLI to invoke LLM if available; otherwise generates
// a stub findings file with structured placeholders.
//
// Exit codes: 0=ok (always — non-blocking)

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'fs';
import { join, resolve } from 'path';
import { createHash } from 'crypto';
import { spawnSync } from 'child_process';

const [,, gateResultArg, repoRoot] = process.argv;

if (!gateResultArg || !repoRoot) {
  process.stderr.write('Usage: findings-generator.mjs <gate_result_json_file> <repo_root>\n');
  process.exit(0); // non-blocking
}

const absRoot = resolve(repoRoot);
const autospecDir = join(absRoot, '.autospec');
mkdirSync(autospecDir, { recursive: true });
const findingsPath = join(autospecDir, 'test-findings.md');

let gateResult = {};
try {
  gateResult = JSON.parse(readFileSync(gateResultArg, 'utf8'));
} catch (e) {
  process.stderr.write(`findings-generator: WARN: cannot parse gate result: ${e.message}\n`);
}

// ── Content-hash gating ───────────────────────────────────────────────────────
const inputHash = createHash('sha256')
  .update(JSON.stringify(gateResult))
  .digest('hex')
  .slice(0, 16);

// Check if existing findings file was generated from same inputs
if (existsSync(findingsPath)) {
  const existing = readFileSync(findingsPath, 'utf8');
  if (existing.includes(`<!-- input-hash: ${inputHash} -->`)) {
    process.stderr.write(`findings-generator: findings unchanged (hash=${inputHash}), skipping\n`);
    process.stdout.write(JSON.stringify({ path: findingsPath, idempotent: true, hash: inputHash }) + '\n');
    process.exit(0);
  }
}

// ── Generate findings ─────────────────────────────────────────────────────────
const timestamp = new Date().toISOString();
const metrics = gateResult?.metrics || {};
const passed = gateResult?.passed ?? 'unknown';
const stage = gateResult?.stage ?? 'unknown';

// Try Codex CLI for LLM-powered findings
let llmFindings = '';
if (!process.env.AUTOSPEC_NO_LLM) {
  const codexResult = spawnSync('codex', [
    'exec',
    '--quiet',
    `Review this test gate result and provide 3-5 actionable findings for improving test coverage:
Stage: ${stage}
Passed: ${passed}
Metrics: ${JSON.stringify(metrics, null, 2)}

Format as a numbered list with: finding, file/area affected, suggested fix.`
  ], { encoding: 'utf8', timeout: 30000 });

  if (codexResult.status === 0 && codexResult.stdout) {
    llmFindings = codexResult.stdout.trim();
  }
}

// Generate structured findings from gate result data
const structuredFindings = [];

if (metrics?.unit) {
  const unit = metrics.unit;
  if (unit.missing_function_tests?.length > 0) {
    structuredFindings.push(`### Missing unit tests for exported functions\n\nThe following functions lack test coverage:\n${unit.missing_function_tests.map(f => `- \`${f}\``).join('\n')}\n\n**Suggested fix:** Add unit tests for each function.`);
  }
  if (unit.lines !== undefined && unit.lines < 90) {
    structuredFindings.push(`### Low line coverage (${unit.lines}%)\n\nLine coverage is below 90%. Review uncovered branches.\n\n**Suggested fix:** Run tests with \`--coverage\` and examine the lcov report.`);
  }
}

if (metrics?.e2e) {
  const e2e = metrics.e2e;
  if (e2e?.ui_element_coverage?.missing?.length > 0) {
    const missing = e2e.ui_element_coverage.missing.slice(0, 5);
    structuredFindings.push(`### UI elements not covered by E2E tests\n\n${missing.map(m => `- \`${m.route}\` → \`${m.selector}\``).join('\n')}\n\n**Suggested fix:** Add Playwright interactions for each element.`);
  }
  if (e2e?.behavior_categories?.missing?.length > 0) {
    structuredFindings.push(`### Missing behavior category coverage\n\nCategories: ${e2e.behavior_categories.missing.join(', ')}\n\n**Suggested fix:** Add annotated tests for each missing category.`);
  }
}

const findingsContent = `<!-- input-hash: ${inputHash} -->
# autospec-test Findings

**Generated:** ${timestamp}
**Stage:** ${stage}
**Gate passed:** ${passed}

## Summary

${passed ? '✓ Gate passed — findings are suggestions for improvement.' : '✗ Gate failed — findings indicate required fixes.'}

${structuredFindings.length > 0 ? structuredFindings.join('\n\n---\n\n') : '### No specific findings generated.\n\nAll coverage metrics met thresholds.'}

${llmFindings ? `\n## LLM Analysis\n\n${llmFindings}` : ''}

---
*Generated by autospec-test findings-generator v1*
`;

writeFileSync(findingsPath, findingsContent, 'utf8');
process.stderr.write(`findings-generator: wrote ${findingsPath}\n`);

process.stdout.write(JSON.stringify({
  path: findingsPath,
  idempotent: false,
  hash: inputHash,
  findings_count: structuredFindings.length,
}) + '\n');
process.exit(0);
