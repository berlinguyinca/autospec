//! Rust types rendered from the protocol schemas into `generated.rs`.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use super::schema_ir::{Node, SchemaSet};

/// Render TypeScript declarations for every entity schema.
///
/// One `export interface` per entity, in the same sorted order as
/// [`render_rust`]. String enums and constants are literal unions, a member the
/// schema does not require is optional (`?`), nested objects are inline type
/// literals. Interfaces cannot express `additionalProperties: false` or
/// `minimum`; the schema validator and the shared fixtures cover both.
// linter:allow-UNWIRED_PUB_ITEM deliberate staging: consumers of the generated types arrive in later T08 issues
pub fn render_ts(set: &SchemaSet) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "{HEADER}");
    for entity in set.entities() {
        if entity == "envelope" {
            continue;
        }
        if let Some(node) = set.node(entity) {
            let _ = writeln!(
                out,
                "\nexport interface {} {}",
                camel(entity),
                ts_type(node, 0)
            );
        }
    }
    out
}

fn ts_key(name: &str) -> String {
    let ident = name
        .chars()
        .next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_' || c == '$')
        && name
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$');
    if ident {
        name.to_string()
    } else {
        format!("\"{name}\"")
    }
}

/// The TypeScript type of a node; `indent` is the nesting depth of the line it starts on.
fn ts_type(node: &Node, indent: usize) -> String {
    match node {
        Node::Object { properties, .. } if properties.is_empty() => {
            "Record<string, unknown>".to_string()
        }
        Node::Object {
            properties,
            required,
            ..
        } => {
            let pad = "  ".repeat(indent + 1);
            let mut out = String::from("{\n");
            for (field, sub) in properties {
                let optional = if required.contains(field) { "" } else { "?" };
                let _ = writeln!(
                    out,
                    "{pad}{}{optional}: {};",
                    ts_key(field),
                    ts_type(sub, indent + 1)
                );
            }
            let _ = write!(out, "{}}}", "  ".repeat(indent));
            out
        }
        Node::Map(sub) => format!("Record<string, {}>", ts_type(sub, indent)),
        Node::Array(sub) => {
            let item = ts_type(sub, indent);
            if item.contains(' ') || item.contains('\n') {
                format!("Array<{item}>")
            } else {
                format!("{item}[]")
            }
        }
        Node::Str {
            enumeration,
            constant,
        } => match (enumeration, constant) {
            (Some(list), _) => list
                .iter()
                .map(|v| format!("\"{v}\""))
                .collect::<Vec<_>>()
                .join(" | "),
            (None, Some(one)) => format!("\"{one}\""),
            (None, None) => "string".to_string(),
        },
        Node::Integer { .. } | Node::Number { .. } => "number".to_string(),
        Node::Boolean => "boolean".to_string(),
    }
}

/// First line of every generated file.
const HEADER: &str = "// @generated by autospec_core::protocol::codegen; do not edit";

/// The line above each generated public item. The linter's wiring check
/// (UNWIRED_PUB_ITEM) cannot see consumers that arrive in later issues.
const STAGING: &str = "// linter:allow-UNWIRED_PUB_ITEM generated protocol types; their consumers arrive in later T08 issues";

const RUST_KEYWORDS: &[&str] = &[
    "abstract", "as", "async", "await", "become", "box", "break", "const", "continue", "crate",
    "do", "dyn", "else", "enum", "extern", "false", "final", "fn", "for", "if", "impl", "in",
    "let", "loop", "macro", "match", "mod", "move", "mut", "override", "priv", "pub", "ref",
    "return", "self", "Self", "static", "struct", "super", "trait", "true", "try", "type",
    "typeof", "unsafe", "unsized", "use", "virtual", "where", "while", "yield",
];

/// `pi-local` -> `PiLocal`, `AGENT-NEVER-STARTED` -> `AgentNeverStarted`,
/// `resource_record` -> `ResourceRecord`. A leading digit gets a `V` prefix.
fn camel(text: &str) -> String {
    let mut out = String::new();
    for part in text.split(|c: char| !c.is_ascii_alphanumeric()) {
        let mut chars = part.chars();
        let Some(first) = chars.next() else { continue };
        out.push(first.to_ascii_uppercase());
        let rest = chars.as_str();
        if rest.chars().any(|c| c.is_ascii_lowercase()) || !first.is_ascii_uppercase() {
            out.push_str(rest);
        } else {
            out.push_str(&rest.to_ascii_lowercase());
        }
    }
    if out.chars().next().is_none_or(|c| c.is_ascii_digit()) {
        out.insert(0, 'V');
    }
    out
}

/// Render the Rust types for every entity schema.
///
/// One struct per entity (the envelope is not an entity: each entity schema
/// carries its own copy of the envelope fields). Objects are closed with
/// `deny_unknown_fields`, string enums and constants become Rust enums, and a
/// member the schema does not require is an `Option`. Output is deterministic:
/// entities and fields are sorted. The types do not encode `minimum` above 0, so
/// the schema validator stays the authority on bounds.
// linter:allow-UNWIRED_PUB_ITEM deliberate staging: consumers of the generated types arrive in later T08 issues
pub fn render_rust(set: &SchemaSet) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "{HEADER}");
    out.push_str("\nuse std::collections::BTreeMap;\n\nuse serde::{Deserialize, Serialize};\n");
    for entity in set.entities() {
        if entity == "envelope" {
            continue;
        }
        if let Some(node) = set.node(entity) {
            out.push('\n');
            render_struct(&camel(entity), node, &mut out);
        }
    }
    out
}

/// Emit `name` as a struct, then the types nested inside it.
fn render_struct(name: &str, node: &Node, out: &mut String) {
    let Node::Object {
        properties,
        required,
        closed,
    } = node
    else {
        return;
    };
    let mut nested = String::new();
    let mut body = String::new();
    for (field, sub) in properties {
        let ty = rust_type(name, field, sub, &mut nested);
        let (ident, rename) = if RUST_KEYWORDS.contains(&field.as_str()) {
            (format!("{field}_"), true)
        } else {
            (field.clone(), false)
        };
        if rename {
            let _ = writeln!(body, "    #[serde(rename = \"{field}\")]");
        }
        if required.contains(field) {
            let _ = writeln!(body, "    pub {ident}: {ty},");
        } else {
            let _ = writeln!(
                body,
                "    #[serde(default, skip_serializing_if = \"Option::is_none\")]"
            );
            let _ = writeln!(body, "    pub {ident}: Option<{ty}>,");
        }
    }
    if !closed {
        body.push_str("    #[serde(flatten)]\n");
        body.push_str("    pub additional: serde_json::Map<String, serde_json::Value>,\n");
    }
    let _ = writeln!(out, "{STAGING}");
    let _ = writeln!(
        out,
        "#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]"
    );
    if *closed {
        out.push_str("#[serde(deny_unknown_fields)]\n");
    }
    if body.is_empty() {
        let _ = writeln!(out, "pub struct {name} {{}}");
    } else {
        let _ = writeln!(out, "pub struct {name} {{\n{body}}}");
    }
    out.push_str(&nested);
}

/// The Rust type for a member, pushing any type it needs into `nested`.
fn rust_type(parent: &str, field: &str, node: &Node, nested: &mut String) -> String {
    let name = format!("{parent}{}", camel(field));
    match node {
        Node::Object { properties, .. } if properties.is_empty() => match node {
            Node::Object { closed: false, .. } => {
                "serde_json::Map<String, serde_json::Value>".to_string()
            }
            _ => {
                nested.push('\n');
                render_struct(&name, node, nested);
                name
            }
        },
        Node::Object { .. } => {
            nested.push('\n');
            render_struct(&name, node, nested);
            name
        }
        Node::Map(sub) => {
            let value = rust_type(parent, &format!("{field}_value"), sub, nested);
            format!("BTreeMap<String, {value}>")
        }
        Node::Array(sub) => {
            let item = rust_type(parent, &format!("{field}_item"), sub, nested);
            format!("Vec<{item}>")
        }
        Node::Str {
            enumeration,
            constant,
        } => {
            let values: Vec<&String> = match (enumeration, constant) {
                (Some(list), _) => list.iter().collect(),
                (None, Some(one)) => vec![one],
                (None, None) => return "String".to_string(),
            };
            nested.push('\n');
            render_enum(&name, &values, nested);
            name
        }
        Node::Integer { minimum } => if minimum.is_some_and(|m| m >= 0.0) {
            "u64"
        } else {
            "i64"
        }
        .to_string(),
        Node::Number { .. } => "f64".to_string(),
        Node::Boolean => "bool".to_string(),
    }
}

fn render_enum(name: &str, values: &[&String], out: &mut String) {
    let _ = writeln!(out, "{STAGING}");
    let _ = writeln!(
        out,
        "#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]"
    );
    let _ = writeln!(out, "pub enum {name} {{");
    let mut used: BTreeMap<String, usize> = BTreeMap::new();
    for value in values {
        let base = camel(value);
        let count = used.entry(base.clone()).or_insert(0);
        *count += 1;
        let variant = if *count == 1 {
            base
        } else {
            format!("{base}{count}")
        };
        let _ = writeln!(out, "    #[serde(rename = \"{value}\")]");
        let _ = writeln!(out, "    {variant},");
    }
    out.push_str("}\n");
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::protocol::schema_ir::load_dir;
    use std::path::{Path, PathBuf};

    fn root() -> PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
    }

    fn rendered() -> String {
        render_rust(&load_dir(&root().join("schemas")).expect("schemas load"))
    }

    /// Regenerate with `AUTOSPEC_REGEN_PROTOCOL=1 cargo test -p autospec-core --lib
    /// protocol::codegen`; the next run compares against the new file.
    #[test]
    fn generated_rs_matches_the_schemas() {
        let fresh = rendered();
        if std::env::var_os("AUTOSPEC_REGEN_PROTOCOL").is_some() {
            std::fs::write(
                root().join("crates/autospec-core/src/protocol/generated.rs"),
                &fresh,
            )
            .expect("write generated.rs");
            return;
        }
        assert!(
            in_sync(&fresh, include_str!("generated.rs")),
            "generated.rs is stale: regenerate with AUTOSPEC_REGEN_PROTOCOL=1"
        );
    }

    /// Regenerate with the same env var as `generated.rs`.
    #[test]
    fn types_d_ts_matches_the_schemas() {
        let fresh = render_ts(&load_dir(&root().join("schemas")).expect("schemas load"));
        if std::env::var_os("AUTOSPEC_REGEN_PROTOCOL").is_some() {
            std::fs::write(root().join("packages/protocol/types.d.ts"), &fresh)
                .expect("write types.d.ts");
            return;
        }
        assert!(
            in_sync(
                &fresh,
                include_str!("../../../../packages/protocol/types.d.ts")
            ),
            "types.d.ts is stale: regenerate with AUTOSPEC_REGEN_PROTOCOL=1"
        );
    }

    fn in_sync(fresh: &str, committed: &str) -> bool {
        fresh == committed
    }

    #[test]
    fn one_changed_byte_is_drift() {
        let fresh = rendered();
        let mut bytes = include_str!("generated.rs").to_string().into_bytes();
        let last = bytes.len() - 2;
        bytes[last] = if bytes[last] == b'x' { b'y' } else { b'x' };
        let altered = String::from_utf8(bytes).expect("ascii");
        assert!(!in_sync(&fresh, &altered));
    }

    fn valid() -> serde_json::Value {
        let path = root().join("tests/fixtures/protocol/valid.json");
        serde_json::from_str(&std::fs::read_to_string(path).expect("valid.json")).expect("json")
    }

    /// Deserialize into `T`, serialize back, and demand the original: a field
    /// the type silently dropped would show as a difference.
    fn roundtrip<T: serde::de::DeserializeOwned + serde::Serialize>(
        entity: &str,
        v: &serde_json::Value,
    ) {
        let typed: T =
            serde_json::from_value(v.clone()).unwrap_or_else(|e| panic!("{entity}: {e}"));
        assert_eq!(
            &serde_json::to_value(&typed).expect("serialize"),
            v,
            "{entity}"
        );
        let mut extra = v.clone();
        extra["surprise"] = serde_json::json!(1);
        assert!(
            serde_json::from_value::<T>(extra).is_err(),
            "{entity}: an extra top-level field must be refused"
        );
    }

    #[test]
    fn every_valid_record_deserializes_into_its_generated_type() {
        use crate::protocol::generated as g;
        let valid = valid();
        let mut seen = 0;
        for (entity, records) in valid.as_object().expect("object") {
            for record in records.as_array().expect("array") {
                seen += 1;
                match entity.as_str() {
                    "mission" => roundtrip::<g::Mission>(entity, record),
                    "task" => roundtrip::<g::Task>(entity, record),
                    "execution" => roundtrip::<g::Execution>(entity, record),
                    "worker" => roundtrip::<g::Worker>(entity, record),
                    "event" => roundtrip::<g::Event>(entity, record),
                    "resource-record" => roundtrip::<g::ResourceRecord>(entity, record),
                    "checkpoint" => roundtrip::<g::Checkpoint>(entity, record),
                    "lease" => roundtrip::<g::Lease>(entity, record),
                    "budget" => roundtrip::<g::Budget>(entity, record),
                    other => panic!("no generated type for {other}"),
                }
            }
        }
        assert!(seen >= 9);
    }

    #[test]
    fn generated_types_refuse_what_the_schema_rejects_structurally() {
        use crate::protocol::generated as g;
        let valid = valid();
        let exec = valid["execution"][0].clone();
        let mut bad_enum = exec.clone();
        bad_enum["executor"] = serde_json::json!("remote-guess");
        assert!(serde_json::from_value::<g::Execution>(bad_enum).is_err());
        let mut bad_nested = exec.clone();
        bad_nested["model_policy"]["extra"] = serde_json::json!(1);
        assert!(serde_json::from_value::<g::Execution>(bad_nested).is_err());
        let mut bad_const = valid["mission"][0].clone();
        bad_const["authority"] = serde_json::json!("autospec-managed");
        assert!(serde_json::from_value::<g::Mission>(bad_const).is_err());
        let mut bad_type = valid["budget"][0].clone();
        bad_type["disk_bytes_limit"] = serde_json::json!("10GiB");
        assert!(serde_json::from_value::<g::Budget>(bad_type).is_err());
        let mut missing = exec;
        missing.as_object_mut().unwrap().remove("execution_id");
        assert!(serde_json::from_value::<g::Execution>(missing).is_err());
    }

    #[test]
    fn variant_names_come_from_the_schema_values() {
        assert_eq!(camel("pi-local"), "PiLocal");
        assert_eq!(camel("AGENT-NEVER-STARTED"), "AgentNeverStarted");
        assert_eq!(camel("RETAINED_FOR_DIAGNOSTICS"), "RetainedForDiagnostics");
        assert_eq!(camel("resource-record"), "ResourceRecord");
        assert_eq!(camel("OK"), "Ok");
        assert_eq!(camel("1abc"), "V1abc");
    }

    #[test]
    fn output_is_deterministic_and_marked_generated() {
        let first = rendered();
        assert_eq!(first, rendered());
        assert_eq!(
            first.lines().next(),
            Some("// @generated by autospec_core::protocol::codegen; do not edit")
        );
    }
}
