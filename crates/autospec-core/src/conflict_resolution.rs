//! Conflict-resolution policy (issue #3663).
//!
//! A blanket "keep both sides" hunk strategy is right for some file shapes —
//! two independent `pub mod` declarations, two changelog entries — and it
//! corrupts others. A `.sha256` golden whose entire content is one value ends
//! up holding the old hash and the new one, and `cargo build` and
//! `cargo fmt --check` both pass over it, because fixture data is not code.
//!
//! The rule this module encodes: **a conflict-resolution strategy is a
//! property of the file, not a property of the merge.**
//!
//! | file shape                          | correct resolution        |
//! | ----------------------------------- | ------------------------- |
//! | append-only list (changelog, …)     | keep both, in order       |
//! | additive declarations (`pub mod`)   | keep both, deduplicated   |
//! | single authoritative value          | regenerate from source    |
//! | generated artefact                  | regenerate, never hand-merge |
//!
//! Auto-resolution **refuses** any file it cannot classify rather than
//! applying a default. For the bottom two rows there is no correct
//! hand-resolution: the file is not the source of truth — something else is,
//! and the file is its shadow. A strategy applied to a file that is not the
//! source of truth is a guess, and the guess is exactly the corruption.

use std::collections::BTreeMap;
use std::path::Path;

/// The shape of a conflicted file. The shape — not the merge — determines the
/// correct resolution strategy.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum FileShape {
    /// Append-only list (changelog, allowlist): entries accumulate in order.
    AppendOnlyList,
    /// Additive declarations (`pub mod`, imports): entries form a set.
    AdditiveDeclarations,
    /// A single authoritative value (checksum, version, lockfile entry). The
    /// file is the shadow of a source of truth that lives elsewhere.
    SingleValue,
    /// A generated artefact whose header names the generator that owns it.
    Generated { generator: String },
    /// Not classifiable from path or header.
    Unknown,
}

impl FileShape {
    pub fn as_str(&self) -> &'static str {
        match self {
            FileShape::AppendOnlyList => "append_only_list",
            FileShape::AdditiveDeclarations => "additive_declarations",
            FileShape::SingleValue => "single_value",
            FileShape::Generated { .. } => "generated",
            FileShape::Unknown => "unknown",
        }
    }
}

/// Comment prefixes that may open a generated-file header.
///
/// Ordered: `<!--` must be tried before `--` and `/*` before any `/` prefix,
/// or the shorter prefix would eat the longer one's first characters.
const HEADER_PREFIXES: [&str; 6] = ["<!--", "/*", "//", "#", "--", ";"];

/// Trailing comment closers. Prose after the closer is not part of the header.
const HEADER_CLOSES: [&str; 2] = ["-->", "*/"];

/// Parse the generated-file header: the file's first line, a comment naming
/// the generator that owns the file.
///
/// Grammar: `<comment-prefix> Generated by <generator>` where
/// `<generator>` is a single whitespace-free token (a script path or a
/// command name). The `<!--` / `/*` forms may close on the same line.
/// Anything looser — prose after the token, a multi-word generator, a header
/// on line two — is not a header, and the file falls back to path-based
/// classification or [`FileShape::Unknown`].
pub fn parse_generator_header(content: &str) -> Option<String> {
    let first = content.lines().next()?;
    let body = first.trim_start();
    // Prose after a comment close (`-->`, `*/`) is not part of the header;
    // cut at whichever closer appears first.
    let mut end = body.len();
    for close in HEADER_CLOSES {
        if let Some(pos) = body.find(close) {
            end = end.min(pos);
        }
    }
    let body = body[..end].trim_end();
    let rest = HEADER_PREFIXES
        .iter()
        .find_map(|prefix| body.strip_prefix(prefix))
        .map(str::trim_start)?;
    let marker = "generated by";
    if !rest.to_ascii_lowercase().starts_with(marker) {
        return None;
    }
    let generator = rest[marker.len()..].trim();
    if generator.is_empty() || generator.contains(char::is_whitespace) {
        return None;
    }
    Some(generator.to_string())
}

fn file_name(path: &str) -> &str {
    path.rsplit('/').next().unwrap_or(path)
}

fn extension_lower(path: &str) -> Option<String> {
    Path::new(file_name(path))
        .extension()
        .and_then(|ext| ext.to_str())
        .map(|ext| ext.to_ascii_lowercase())
}

/// Whether `path` names a single-value file by its file name or extension:
/// a checksum golden (`.sha256`, `.sha512`, `.md5`) or a version file.
///
/// Deliberately path-based, not content-based: the corrupted form of a
/// `.sha256` golden — two hashes — must still classify as single-value so the
/// shape check can flag it.
pub fn is_single_value_path(path: &str) -> bool {
    let lower = file_name(path).to_ascii_lowercase();
    matches!(lower.as_str(), "version" | "version.txt" | ".version")
        || matches!(
            extension_lower(path).as_deref(),
            Some("sha256" | "sha512" | "md5")
        )
}

/// Classify a conflicted file by its path and content.
///
/// Conservative on purpose: anything not confidently recognizable is
/// [`FileShape::Unknown`], and unknown files are refused, not defaulted.
pub fn classify_file(path: &str, content: &str) -> FileShape {
    if let Some(generator) = parse_generator_header(content) {
        return FileShape::Generated { generator };
    }
    if is_single_value_path(path) {
        return FileShape::SingleValue;
    }
    let lower = file_name(path).to_ascii_lowercase();
    match lower.as_str() {
        "changelog" | "changelog.md" | "changelog.txt" | "allowlist" => {
            return FileShape::AppendOnlyList;
        }
        "mod.rs" | "lib.rs" => return FileShape::AdditiveDeclarations,
        _ => {}
    }
    if lower.ends_with(".allowlist") {
        return FileShape::AppendOnlyList;
    }
    FileShape::Unknown
}

/// The resolution a conflicted file's shape dictates.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ResolutionPlan {
    /// Append-only list: keep both sides, in order.
    KeepBothInOrder,
    /// Additive declarations: keep both sides, deduplicated.
    KeepBothDeduplicated,
    /// Single authoritative value or generated artefact: regenerate from
    /// source. `generator` is the header-declared name when the file has one;
    /// otherwise the repository registry must supply it by path.
    Regenerate { generator: Option<String> },
    /// The file's shape could not be classified. Auto-resolution refuses
    /// rather than applying a default — a default strategy here is the
    /// corruption #3663 describes.
    Refuse { reason: String },
}

impl ResolutionPlan {
    pub fn as_str(&self) -> &'static str {
        match self {
            ResolutionPlan::KeepBothInOrder => "keep_both_in_order",
            ResolutionPlan::KeepBothDeduplicated => "keep_both_deduplicated",
            ResolutionPlan::Regenerate { .. } => "regenerate",
            ResolutionPlan::Refuse { .. } => "refuse",
        }
    }
}

/// Map a file shape to its resolution plan. The table in #3663, verbatim:
/// keep-both (two flavours) for the two list shapes, regeneration for the two
/// shadow shapes, and refusal for everything the classifier did not claim.
pub fn resolution_for(shape: &FileShape) -> ResolutionPlan {
    match shape {
        FileShape::AppendOnlyList => ResolutionPlan::KeepBothInOrder,
        FileShape::AdditiveDeclarations => ResolutionPlan::KeepBothDeduplicated,
        FileShape::SingleValue => ResolutionPlan::Regenerate { generator: None },
        FileShape::Generated { generator } => ResolutionPlan::Regenerate {
            generator: Some(generator.clone()),
        },
        FileShape::Unknown => ResolutionPlan::Refuse {
            reason: "unclassifiable file shape: no conflict-resolution strategy applies, and a \
                     default would be a guess"
                .to_string(),
        },
    }
}

/// The repository's generator registry: which generator owns which files.
///
/// A single-value file (a `.sha256` golden) has no room for a header, so the
/// registry — not the file — says where its source of truth lives.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct GeneratorRegistry {
    /// Exact file path, or a directory prefix ending in `/` (everything under
    /// it) → generator name.
    owners: BTreeMap<String, String>,
}

impl GeneratorRegistry {
    pub fn new() -> Self {
        Self::default()
    }

    /// Record that `generator` owns `path` — an exact file path, or a
    /// directory prefix ending in `/` covering everything under it.
    pub fn register(&mut self, path: &str, generator: &str) {
        self.owners.insert(path.to_string(), generator.to_string());
    }

    /// The generator that owns `path`: an exact entry wins, else the longest
    /// matching directory prefix. `None` when nothing owns the file — and
    /// nothing owning the file means regeneration is refused, not guessed.
    pub fn generator_for(&self, path: &str) -> Option<&str> {
        if let Some(generator) = self.owners.get(path) {
            return Some(generator.as_str());
        }
        self.owners
            .iter()
            .filter(|(prefix, _)| prefix.ends_with('/') && path.starts_with(prefix.as_str()))
            .max_by_key(|(prefix, _)| prefix.len())
            .map(|(_, generator)| generator.as_str())
    }
}

/// Executes a named generator. The core stays platform-agnostic; the caller
/// supplies the shell (or a test double).
pub trait GeneratorRunner {
    /// Run the named generator. `Err` when it is unknown or fails.
    fn run(&self, generator: &str) -> Result<(), String>;
}

/// What auto-resolution did with a conflicted file.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum AutoResolutionOutcome {
    /// A text merge is correct for this shape; the plan names the flavour
    /// (in order, or deduplicated).
    TextMerge { plan: ResolutionPlan },
    /// The file is the shadow of its source of truth: the generator was run
    /// and its result taken, which cannot guess wrong.
    Regenerated { generator: String },
}

/// Why auto-resolution could not take a conflicted file.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum AutoResolutionError {
    /// The file's shape could not be classified. A default strategy is
    /// exactly the corruption #3663 describes; a human resolves this one.
    RefusedUnclassifiable { path: String, reason: String },
    /// A single-value or generated file that no registered generator owns.
    NoGenerator { path: String },
    /// The generator failed.
    GeneratorFailed {
        path: String,
        generator: String,
        error: String,
    },
    /// The generator ran but the file it left behind fails the shape check.
    PostCheckFailed { path: String, findings: Vec<String> },
    /// The regenerated file could not be read back.
    UnreadableAfterGeneration { path: String },
}

/// The resolution step for one conflicted file.
///
/// Classifies the file, then applies the strategy its shape dictates. For the
/// keep-both shapes it returns the text-merge plan. For the regenerate shapes
/// it looks the generator up — the file's header first, then the repository
/// registry — runs it, and takes its result: re-reading the file through
/// `read_back` and running the shape check on what the generator left
/// behind, so a generator that produces garbage is rejected rather than
/// merged.
pub fn auto_resolve(
    path: &str,
    content: &str,
    registry: &GeneratorRegistry,
    runner: &dyn GeneratorRunner,
    read_back: &dyn Fn(&str) -> Option<String>,
) -> Result<AutoResolutionOutcome, AutoResolutionError> {
    let shape = classify_file(path, content);
    match resolution_for(&shape) {
        plan @ (ResolutionPlan::KeepBothInOrder | ResolutionPlan::KeepBothDeduplicated) => {
            Ok(AutoResolutionOutcome::TextMerge { plan })
        }
        ResolutionPlan::Regenerate {
            generator: declared,
        } => {
            let generator = declared
                .as_deref()
                .or_else(|| registry.generator_for(path))
                .ok_or(AutoResolutionError::NoGenerator {
                    path: path.to_string(),
                })?;
            runner
                .run(generator)
                .map_err(|error| AutoResolutionError::GeneratorFailed {
                    path: path.to_string(),
                    generator: generator.to_string(),
                    error,
                })?;
            let regenerated =
                read_back(path).ok_or_else(|| AutoResolutionError::UnreadableAfterGeneration {
                    path: path.to_string(),
                })?;
            let findings = check_single_value_file(path, &regenerated);
            if findings.is_empty() {
                Ok(AutoResolutionOutcome::Regenerated {
                    generator: generator.to_string(),
                })
            } else {
                Err(AutoResolutionError::PostCheckFailed {
                    path: path.to_string(),
                    findings,
                })
            }
        }
        ResolutionPlan::Refuse { reason } => Err(AutoResolutionError::RefusedUnclassifiable {
            path: path.to_string(),
            reason,
        }),
    }
}

/// Shape check for single-value files: a checksum, version, or lockfile entry
/// holds exactly one non-blank line.
///
/// A `.sha256` golden holding two hashes — the corruption #3663 describes —
/// is malformed regardless of what it contains, and it is one `wc -l` away
/// from being caught: exactly this check. Files whose shape is not
/// single-value return no findings.
pub fn check_single_value_file(path: &str, content: &str) -> Vec<String> {
    if !is_single_value_path(path) {
        return Vec::new();
    }
    let values: Vec<&str> = content
        .lines()
        .filter(|line| !line.trim().is_empty())
        .collect();
    match values.len() {
        0 => vec![format!(
            "{path}: malformed single-value file: no value where exactly 1 line is allowed"
        )],
        1 => Vec::new(),
        n => vec![format!(
            "{path}: malformed single-value file: {n} lines where exactly 1 is allowed \
             (a checksum/version holds a single value; regenerate it instead of merging)"
        )],
    }
}

/// One finding from the shape gate.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ShapeGateFinding {
    pub path: String,
    pub detail: String,
}

/// Gate-set entry (#3663): run the single-value shape check over a population
/// of files and report every member that fails it.
///
/// The habit this gate closes: applying an operation to a population without
/// checking that every member of the population admits it.
pub fn shape_gate(files: &[(String, String)]) -> Vec<ShapeGateFinding> {
    files
        .iter()
        .flat_map(|(path, content)| {
            check_single_value_file(path, content)
                .into_iter()
                .map(|detail| ShapeGateFinding {
                    path: path.clone(),
                    detail,
                })
        })
        .collect()
}

