    #[test]
    fn the_shape_gate_reports_every_malformed_member_of_the_population() {
        let files = vec![
            ("a.sha256".to_string(), HASH_A.to_string()),
            ("b.sha256".to_string(), CORRUPTED_GOLDEN.to_string()),
            (
                "c.sha256".to_string(),
                format!("{HASH_A}\n{HASH_B}\n{HASH_A}"),
            ),
            ("changelog.md".to_string(), "a\nb\n".to_string()),
        ];
        let findings = shape_gate(&files);
        assert_eq!(
            findings.iter().map(|f| f.path.as_str()).collect::<Vec<_>>(),
            vec!["b.sha256", "c.sha256"]
        );
    }
