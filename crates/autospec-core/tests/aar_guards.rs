/// Exceptions exist, but only where an operator wrote one down with a reason.
#[test]
fn an_explicit_exception_suppresses_the_guard() {
    let policy = EditPolicy::default()
        .with_exception("src/generated.rs", "generated by the schema tool")
        .expect("reason supplied");
    let mut guard = EditGuard::new(policy);

    let violations = guard.observe(&EditAction::Edit {
        path: "src/generated.rs".to_string(),
        lines: 5_000,
    });

    assert!(violations.is_empty());
    assert_eq!(
        guard.policy().exception_reason("src/generated.rs"),
        Some("generated by the schema tool")
    );
}

#[test]
fn an_exception_without_a_reason_is_rejected() {
    assert!(EditPolicy::default().with_exception("src/a.rs", "  ").is_err());
}

#[test]
fn a_second_edit_in_one_step_breaks_the_one_logical_change_rule() {
    let mut guard = EditGuard::new(EditPolicy::default());
    for path in ["src/a.rs", "src/b.rs"] {
        guard.observe(&EditAction::Read {
            path: path.to_string(),
        });
    }

    guard.observe(&EditAction::Edit {
        path: "src/a.rs".to_string(),
        lines: 5,
    });
    let violations = guard.observe(&EditAction::Edit {
        path: "src/b.rs".to_string(),
        lines: 5,
    });

    assert!(violations
        .iter()
        .any(|violation| violation.code == "one_logical_change_per_step"));
}

#[test]
fn creating_a_file_after_an_edit_also_breaks_the_one_logical_change_rule() {
    let mut guard = EditGuard::new(EditPolicy::default());
    guard.observe(&EditAction::Read {
        path: "src/a.rs".to_string(),
    });
    guard.observe(&EditAction::Edit {
        path: "src/a.rs".to_string(),
        lines: 5,
    });

    let violations = guard.observe(&EditAction::Create {
        path: "src/b.rs".to_string(),
        lines: 20,
    });

    assert!(violations
        .iter()
        .any(|violation| violation.code == "one_logical_change_per_step"));
}

