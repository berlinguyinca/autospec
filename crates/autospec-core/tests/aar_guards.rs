/// The rule agents ignore most often: budget left is not a reason to continue.
#[test]
fn meeting_every_acceptance_criterion_stops_execution_immediately() {
    let reason = evaluate_stop(
        &StopPolicy::default(),
        &ExecutionProgress {
            steps: 2,
            acceptance_criteria_total: 3,
            acceptance_criteria_met: 3,
            ..ExecutionProgress::default()
        },
    );

    assert_eq!(reason, Some(StopReason::AcceptanceMet));
    assert!(reason.expect("stopped").is_success());
}

#[test]
fn exhausting_steps_tokens_or_retries_stops_execution() {
    let policy = StopPolicy::default();

    assert_eq!(
        evaluate_stop(
            &policy,
            &ExecutionProgress {
                steps: policy.max_steps,
                ..ExecutionProgress::default()
            }
        ),
        Some(StopReason::MaxSteps)
    );
    assert_eq!(
        evaluate_stop(
            &policy,
            &ExecutionProgress {
                tokens: policy.max_tokens,
                ..ExecutionProgress::default()
            }
        ),
        Some(StopReason::MaxTokens)
    );
    assert_eq!(
        evaluate_stop(
            &policy,
            &ExecutionProgress {
                retries: policy.max_retries + 1,
                ..ExecutionProgress::default()
            }
        ),
        Some(StopReason::MaxRetries)
    );
}

#[test]
fn an_unresolved_thrash_signal_stops_execution() {
    let reason = evaluate_stop(
        &StopPolicy::default(),
        &ExecutionProgress {
            steps: 1,
            unresolved_thrash_signals: 1,
            ..ExecutionProgress::default()
        },
    );

    assert_eq!(reason, Some(StopReason::Thrashing));
    assert!(!reason.expect("stopped").is_success());
}

#[test]
fn execution_with_budget_remaining_and_work_outstanding_continues() {
    let reason = evaluate_stop(
        &StopPolicy::default(),
        &ExecutionProgress {
            steps: 3,
            acceptance_criteria_total: 4,
            acceptance_criteria_met: 2,
            ..ExecutionProgress::default()
        },
    );

    assert_eq!(reason, None);
}
