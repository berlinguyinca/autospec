#[test]
fn claim_parser_handles_ranges_and_singletons() {
    assert_eq!(
        claim_from_words("ran steps 1-3 of 7"),
        GateClaim::RanSteps {
            ran: vec![1, 2, 3],
            total: 7
        }
    );
    assert_eq!(
        claim_from_words("ran step 5 of 7"),
        GateClaim::RanSteps {
            ran: vec![5],
            total: 7
        }
    );
    assert_eq!(
        claim_from_words("ran steps 1-3, 5, 7-8 of 8"),
        GateClaim::RanSteps {
            ran: vec![1, 2, 3, 5, 7, 8],
            total: 8
        }
    );
    // Wording that states no coverage is read as the bare claim: the burden
    // of proof is on the claimant, not on the reader.
    assert_eq!(
        claim_from_words("the gate is clean"),
        GateClaim::GateIsClean
    );
    assert_eq!(claim_from_words("gate passed"), GateClaim::GateIsClean);
}

#[test]
fn bare_clean_claim_is_overstated_when_coverage_is_partial() {
    let job = incident_job();
    let measured = coverage(&incident_gate(), &job);
    let verdict = challenge_claim(&claim_from_words("the gate is clean"), &measured, &job);
    match &verdict {
        ClaimVerdict::Overstated { restatement } => {
            assert!(
                restatement.contains("ran steps 1-3 of 7"),
                "restatement must state the coverage actually measured: {restatement}"
            );
            assert!(restatement.contains("skipped 4-7"));
        }
        other => panic!("a clean claim over a partial gate must be Overstated, got {other:?}"),
    }
    assert!(verdict.line().starts_with("WARN:"));
}

#[test]
fn correct_coverage_claim_is_accepted() {
    let job = incident_job();
    let measured = coverage(&full_gate(), &job);
    assert_eq!(
        challenge_claim(&claim_from_words("the gate is clean"), &measured, &job),
        ClaimVerdict::Accepted,
        "a gate that runs every step may be called clean"
    );
    let partial = coverage(&incident_gate(), &job);
    assert_eq!(
        challenge_claim(&claim_from_words("ran steps 1-3 of 7"), &partial, &job),
        ClaimVerdict::Accepted
    );
}

#[test]
fn wrong_coverage_claim_is_rejected() {
    let job = incident_job();
    let partial = coverage(&incident_gate(), &job);
    // Claims every step ran.
    let v = challenge_claim(&claim_from_words("ran steps 1-7 of 7"), &partial, &job);
    assert!(matches!(v, ClaimVerdict::WrongCoverage { .. }), "{v:?}");
    assert!(v.line().starts_with("WARN:"));
    // Right steps, wrong denominator.
    assert!(matches!(
        challenge_claim(&claim_from_words("ran steps 1-3 of 3"), &partial, &job),
        ClaimVerdict::WrongCoverage { .. }
    ));
}

