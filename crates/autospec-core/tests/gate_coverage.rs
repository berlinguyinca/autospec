#[test]
fn purpose_named_job_is_admissible() {
    let job = control_job();
    let verdict = name_policy(&job);
    assert_eq!(verdict, NamePolicy::PurposeNamed);
    assert!(!verdict.is_trap());
    assert!(verdict.line(&job).starts_with("OK:"));
}

#[test]
fn incident_name_is_a_trap_naming_every_omitted_step() {
    let job = incident_job();
    let verdict = name_policy(&job);
    match &verdict {
        NamePolicy::PartialEnumeration {
            named_count,
            total_steps,
            not_listed,
            unbacked,
            ..
        } => {
            assert_eq!((*named_count, *total_steps), (3, 7));
            // Every omitted step is named in the verdict: the reader is not
            // left to guess what the label left out.
            assert_eq!(
                *not_listed,
                vec![
                    "ignored tests",
                    "schema check",
                    "pinned digests",
                    "ci skeleton"
                ]
            );
            assert!(unbacked.is_empty());
        }
        other => panic!("expected a partial enumeration, got {other:?}"),
    }
    assert!(verdict.is_trap());
    let line = verdict.line(&job);
    assert!(line.contains("names 3 of its 7 steps"), "{line}");
    assert!(line.contains("ci skeleton"), "{line}");
    assert!(
        line.contains("naming some of the steps is worse than naming none"),
        "{line}"
    );
}

#[test]
fn partial_enumeration_is_a_trap_even_when_every_token_is_real() {
    // The #4197 lint compares an enumerating name AGAINST the steps and passes
    // when every token is a real step. That is the weaker rule: this name names
    // 6 of 7 real steps and is still the trap, because the harm is the omission
    // and the reader runs what is written.
    let mut job = incident_job();
    job.name = format!(
        "Rust baseline ({})",
        ["fmt", "clippy", "test"]
            .iter()
            .map(|s| s.to_string())
            .chain(job.steps[3..6].iter().map(|s| s.name.clone()))
            .collect::<Vec<_>>()
            .join(" / ")
    );
    let verdict = name_policy(&job);
    assert!(verdict.is_trap(), "{verdict:?}");
    match verdict {
        NamePolicy::PartialEnumeration {
            named_count,
            total_steps,
            not_listed,
            unbacked,
            ..
        } => {
            assert_eq!((named_count, total_steps), (6, 7));
            assert_eq!(not_listed, ["ci skeleton"]);
            assert!(unbacked.is_empty(), "{unbacked:?}");
        }
        other => panic!("expected a partial enumeration, got {other:?}"),
    }
}

#[test]
fn generated_enumeration_is_admissible() {
    // A name generated from the steps cannot fall behind them: the defect that
    // #4197 caught (the omitted `test`) is impossible by construction here.
    let mut job = incident_job();
    job.name = derive_name(&job);
    let verdict = name_policy(&job);
    assert_eq!(verdict, NamePolicy::GeneratedEnumeration);
    assert!(!verdict.is_trap());
    assert!(verdict.line(&job).starts_with("OK:"));
}

#[test]
fn enumeration_is_case_insensitive_against_step_names() {
    let mut job = incident_job();
    job.name =
        "Rust baseline (FMT / Clippy / TEST / ignored tests / schema check / pinned digests / ci skeleton)".to_string();
    assert_eq!(name_policy(&job), NamePolicy::GeneratedEnumeration);
}

#[test]
fn a_label_listing_a_step_ci_no_longer_runs_is_a_trap() {
    // The name ran ahead of the job: the label still promises a step that was
    // removed from CI. Nothing in the label can be trusted as the contract.
    let mut job = CiJob {
        id: "node-baseline".into(),
        name: "Node baseline".into(),
        steps: vec![step("install", "npm ci"), step("typecheck", "tsc --noEmit")],
    };
    job.name = "Node baseline (install / typecheck / audit)".into();
    match name_policy(&job) {
        NamePolicy::PartialEnumeration {
            unbacked,
            named_count,
            total_steps,
            ..
        } => {
            assert_eq!(unbacked, ["audit"]);
            assert_eq!((named_count, total_steps), (2, 2));
        }
        other => panic!("expected a partial enumeration, got {other:?}"),
    }
}

#[test]
fn unnamed_steps_are_reported_by_position() {
    let mut job = CiJob {
        id: "node-baseline".into(),
        name: "Node baseline".into(),
        steps: vec![
            step("install", "npm ci"),
            step("", "npm run codegen"),
            step("build", "npm run build"),
        ],
    };
    job.name = "Node baseline (install)".into();
    match name_policy(&job) {
        NamePolicy::PartialEnumeration { not_listed, .. } => {
            assert_eq!(not_listed, ["step 2 (unnamed)", "build"])
        }
        other => panic!("expected a partial enumeration, got {other:?}"),
    }
}

