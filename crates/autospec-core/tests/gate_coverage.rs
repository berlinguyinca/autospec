#[test]
fn artifact_check_dropped_by_the_gate_is_reported_with_its_ci_step() {
    // CI ran `check-pinned-digests.sh` at step 6; the transcribed gate does
    // not run it at all. The finding must name the step CI runs it at.
    let drift = artifact_drift(&incident_job(), &incident_gate(), &bindings_contract());
    match &drift {
        ArtifactDrift::CheckNotRun {
            artifact,
            command,
            ci_step,
        } => {
            assert_eq!(artifact, "inferweave-bindings-0.1.0.tgz");
            assert_eq!(command, "bash scripts/check-pinned-digests.sh");
            assert_eq!(*ci_step, Some(6), "CI runs the check at step 6");
        }
        other => panic!("dropped pin check must be CheckNotRun, got {other:?}"),
    }
    let line = drift.line(&bindings_contract());
    assert!(line.starts_with("WARN:"));
    assert!(line.contains("CI runs it at step 6"), "{line}");
    assert!(
        line.contains("EINTEGRITY"),
        "the line must name the failure the check prevents: {line}"
    );
}

#[test]
fn artifact_check_covered_when_gate_runs_it() {
    let drift = artifact_drift(&incident_job(), &full_gate(), &bindings_contract());
    match &drift {
        ArtifactDrift::Covered { command } => {
            assert_eq!(command, "bash scripts/check-pinned-digests.sh")
        }
        other => panic!("full gate runs the pin check, got {other:?}"),
    }
    assert!(drift.line(&bindings_contract()).starts_with("OK:"));
}

#[test]
fn a_contract_with_no_declared_check_is_missing_check() {
    // The contract itself is incomplete: it regenerates an artifact and
    // names no check for its pin. Construction accepts it (the omission is
    // the state under audit), and the verdict names the failure it allows.
    let contract = ArtifactContract::new(
        "inferweave-bindings-0.1.0.tgz",
        "apps/web/package-lock.json",
        "npm error code EINTEGRITY inside the web image publish job",
        vec![5],
        None,
    )
    .expect("artifact, pin and failure mode are present");
    let drift = artifact_drift(&incident_job(), &full_gate(), &contract);
    match &drift {
        ArtifactDrift::MissingCheck {
            artifact,
            pin_file,
            regenerated_by,
        } => {
            assert_eq!(artifact, "inferweave-bindings-0.1.0.tgz");
            assert_eq!(pin_file, "apps/web/package-lock.json");
            assert_eq!(regenerated_by, &vec![5]);
        }
        other => panic!("a contract with no check must be MissingCheck, got {other:?}"),
    }
    assert!(drift
        .line(&contract)
        .contains("no cross-artifact drift check"));
}

#[test]
fn a_gate_that_regenerates_nothing_has_no_obligation() {
    let contract = ArtifactContract::new(
        "some-other-artifact.tar.gz",
        "elsewhere/pin.txt",
        "unrelated drift",
        vec![],
        None,
    )
    .expect("artifact, pin and failure mode are present");
    let drift = artifact_drift(&incident_job(), &incident_gate(), &contract);
    assert!(matches!(drift, ArtifactDrift::NotRegenerated));
    assert!(drift.line(&contract).starts_with("OK:"));
}

#[test]
fn contracts_refuse_to_be_constructed_empty() {
    let err: ContractError =
        ArtifactContract::new("", "apps/web/package-lock.json", "drift", vec![5], None)
            .expect_err("an unnamed artifact is not a contract");
    assert_eq!(err.field(), "artifact");

    let err = DriftCheck::new("bash scripts/check-pinned-digests.sh", "")
        .expect_err("a drift check with no rationale is a habit, not a contract");
    assert_eq!(err.field(), "rationale");
    assert!(err.to_string().contains("rationale"));
}

#[test]
fn step_ranges_group_consecutive_indices() {
    // The coverage statement's formatting primitive: "1-3, 5, 7-8" reads as
    // coverage, a bare list of numbers does not.
    assert_eq!(format_step_ranges(&[1, 2, 3, 5, 7, 8]), "1-3, 5, 7-8");
    assert_eq!(format_step_ranges(&[4, 5, 6, 7]), "4-7");
    assert_eq!(format_step_ranges(&[6]), "6");
    assert_eq!(format_step_ranges(&[]), "none");
}

