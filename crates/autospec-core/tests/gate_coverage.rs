//! Local-gate coverage (issue #4304).
//!
//! The incident: the CI job was named `"Rust baseline (fmt / clippy /
//! test)"` and ran seven steps. The engineer — two months after #4197 told
//! him the steps are the contract — wrote a local gate from the three
//! commands in the label, ran it, and reported the gate clean. Steps 4-7
//! never ran locally: the `--ignored` tests, a `schema-gen --check`
//! regenerate-and-diff, the pinned-digest check, and `test-ci-skeleton.sh`,
//! which is the step that caught the defect. The fix was a two-line pin.
//!
//! The regression tests run in the configuration the bug required: a job
//! whose name enumerates three of its seven steps and a gate transcribed
//! from that name. On a job with a purpose-only name and a generated gate
//! (the control), every check agrees.

use autospec_core::ci_name_drift::{derive_name, CiJob, CiStep};
use autospec_core::gate_coverage::{
    artifact_drift, audit, challenge_claim, claim_from_words, coverage, derive_gate,
    format_step_ranges, name_policy, render_gate_script, ArtifactContract, ArtifactDrift,
    ClaimVerdict, ContractError, DriftCheck, GateClaim, GateEquivalence, NamePolicy,
};

/// The incident configuration: a job whose name enumerates three of its seven
/// steps. Steps 4-7 exist in the workflow and appear in no label.
fn incident_job() -> CiJob {
    CiJob {
        id: "rust-baseline".into(),
        name: "Rust baseline (fmt / clippy / test)".into(),
        steps: vec![
            step("fmt", "cargo fmt --all --check"),
            step("clippy", "cargo clippy --workspace --all-targets"),
            step("test", "cargo test --workspace"),
            step("ignored tests", "cargo test --workspace -- --ignored"),
            step("schema check", "schema-gen --check"),
            step("pinned digests", "bash scripts/check-pinned-digests.sh"),
            step("ci skeleton", "bash tests/test-ci-skeleton.sh"),
        ],
    }
}

fn step(name: &str, run: &str) -> CiStep {
    CiStep {
        name: name.into(),
        run: run.into(),
    }
}

/// The gate the engineer wrote by reading the label: steps 1-3, no more.
fn incident_gate() -> Vec<String> {
    vec![
        "cargo fmt --all --check".into(),
        "cargo clippy --workspace --all-targets".into(),
        "cargo test --workspace".into(),
    ]
}

/// The correct gate: every `run:` step of the job, generated from the job.
fn full_gate() -> Vec<String> {
    derive_gate(&incident_job())
}

/// The control: a purpose-named job — no parenthetical enumeration to copy.
fn control_job() -> CiJob {
    CiJob {
        id: "rust-baseline".into(),
        name: "Rust baseline".into(),
        steps: vec![
            step("", "cargo fmt --all --check"),
            step("", "cargo clippy --workspace --all-targets"),
            step("", "cargo test --workspace"),
        ],
    }
}

/// The name the steps derive to — the remedy #4304 offers for a partial
/// label, and the name a complete gate must carry.
const FULL_NAME: &str = "Rust baseline (fmt / clippy / test / ignored tests / schema check / pinned digests / ci skeleton)";

/// The #4304 cross-artifact contract: the bindings tarball is regenerated by
/// the schema step and its digest is pinned in the web lockfile. CI checked
/// the pin at step 6; the transcribed gate dropped it.
fn bindings_contract() -> ArtifactContract {
    ArtifactContract::new(
        "inferweave-bindings-0.1.0.tgz",
        "apps/web/package-lock.json",
        "npm error code EINTEGRITY inside the web image publish job, far from its cause",
        vec![5],
        Some(
            DriftCheck::new(
                "bash scripts/check-pinned-digests.sh",
                "the regenerated tarball no longer matches the digest pinned in the lockfile",
            )
            .expect("check has a command and a rationale"),
        ),
    )
    .expect("contract names its artifact, pin and failure mode")
}

// ---------------------------------------------------------------- invariant 1

#[test]
fn gate_is_derived_from_steps_not_from_the_name() {
    let gate = derive_gate(&incident_job());
    assert_eq!(gate.len(), 7, "the job has seven steps");
    assert!(
        gate.contains(&"bash tests/test-ci-skeleton.sh".to_string()),
        "the step that caught the defect must be in the generated gate"
    );
    assert_eq!(gate, incident_job().command_list());
}

#[test]
fn incident_gate_covers_three_of_seven_and_says_so() {
    let measured = coverage(&incident_gate(), &incident_job());
    assert_eq!(measured.ran, vec![1, 2, 3]);
    assert_eq!(measured.skipped, vec![4, 5, 6, 7]);
    assert!(measured.extra.is_empty());
    assert_eq!(
        measured.equivalence(),
        GateEquivalence::Partial {
            skipped: vec![4, 5, 6, 7]
        }
    );
}

#[test]
fn full_gate_is_the_same_gate() {
    let measured = coverage(&full_gate(), &incident_job());
    assert_eq!(measured.equivalence(), GateEquivalence::Same);
    assert!(measured.skipped.is_empty());
}

#[test]
fn extra_command_makes_the_gate_divergent() {
    let mut gate = incident_gate();
    gate.push("cargo +nightly miri test".into());
    let measured = coverage(&gate, &incident_job());
    assert_eq!(
        measured.equivalence(),
        GateEquivalence::Divergent {
            skipped: vec![4, 5, 6, 7],
            extra: vec!["cargo +nightly miri test".into()],
        }
    );
    assert!(measured
        .statement(&incident_job())
        .contains("no CI step runs"));
}

#[test]
fn coverage_statement_is_scoped_never_clean() {
    let measured = coverage(&incident_gate(), &incident_job());
    assert_eq!(
        measured.statement(&incident_job()),
        "ran steps 1-3 of 7 (skipped 4-7)"
    );
    let full = coverage(&full_gate(), &incident_job());
    assert_eq!(
        full.statement(&incident_job()),
        "ran all 7 steps of job 'rust-baseline'"
    );
}

#[test]
fn paired_lists_show_both_lists_when_automation_is_impossible() {
    let measured = coverage(&incident_gate(), &incident_job());
    let lines = measured.paired_lists(&incident_job());
    // header + one line per CI step.
    assert_eq!(lines.len(), 8);
    assert!(lines[0].contains("defines 7 steps; this gate runs 3"));
    assert!(lines[1].contains("[    RAN]"));
    assert!(lines[4].contains("[SKIPPED]"));
    assert!(lines[4].contains("cargo test --workspace -- --ignored"));
    // A gate command with no CI step behind it is shown as added.
    let mut gate = full_gate();
    gate.push("echo local-only".into());
    let diverged = coverage(&gate, &incident_job()).paired_lists(&incident_job());
    assert!(diverged.last().unwrap().contains("GATE extra"));
    assert!(diverged.last().unwrap().contains("echo local-only"));
}

#[test]
fn rendered_gate_carries_its_own_coverage() {
    let script = render_gate_script(&incident_job());
    assert!(script.contains("set -euo pipefail"));
    assert!(script.contains("gate step 1/7: fmt"));
    assert!(script.contains("gate step 6/7: pinned digests"));
    assert!(script.contains("gate step 7/7: ci skeleton"));
    assert!(script.contains("bash tests/test-ci-skeleton.sh"));
    // A step with no name still gets a numbered header.
    let unnamed = render_gate_script(&control_job());
    assert!(unnamed.contains("gate step 2/3: step 2"));
}

#[test]
fn rendered_gate_escapes_quoting_in_labels() {
    let mut job = control_job();
    job.steps[0].name = r#"run "tests" $HOME `id`"#.into();
    let script = render_gate_script(&job);
    // Nothing in the label terminates the echo's quoting: every risky
    // character is escaped, so the generated script cannot execute its own
    // step names.
    assert!(script.contains(r#"run \"tests\" \$HOME \`id\`"#));
}

