#[test]
fn audit_of_the_incident_gate_reports_the_findings() {
    let lines = audit(&incident_job(), &incident_gate(), &[bindings_contract()]);
    let text = lines.join("\n");
    // Coverage: the gate says what it skipped.
    assert!(text.contains("ran steps 1-3 of 7"), "{text}");
    assert!(text.contains("SKIPPED"), "{text}");
    // Name policy: the partial enumeration is named as the trap.
    assert!(
        text.contains("naming some of the steps is worse than naming none"),
        "{text}"
    );
    // Pin check: named with the CI step that runs it.
    assert!(text.contains("CI runs it at step 6"), "{text}");
    // Verdict: three findings, and it never says "clean".
    let last = lines.last().expect("audit emits a verdict line");
    assert!(last.starts_with("WARN: 3 finding(s)"), "{last}");
    assert!(!text.contains("the gate is the CI gate"), "{text}");
}

#[test]
fn audit_of_the_full_gate_is_clean() {
    // The control: a purpose-named job whose gate runs every step and whose
    // one regenerated artifact has its pin check in the gate.
    let job = CiJob {
        id: "node-baseline".into(),
        name: "Node baseline".into(),
        steps: vec![
            step("install", "npm ci"),
            step("build", "npm run build"),
            step("pin check", "bash scripts/check-pinned-digests.sh"),
        ],
    };
    let gate = derive_gate(&job);
    let contract = ArtifactContract::new(
        "inferweave-bindings-0.1.0.tgz",
        "apps/web/package-lock.json",
        "npm error code EINTEGRITY inside the web image publish job",
        vec![2],
        Some(
            DriftCheck::new(
                "bash scripts/check-pinned-digests.sh",
                "the regenerated tarball no longer matches the digest pinned in the lockfile",
            )
            .expect("check has a command and a rationale"),
        ),
    )
    .expect("contract names its artifact, pin and failure mode");
    let lines = audit(&job, &gate, &[contract]);
    let text = lines.join("\n");
    let last = lines.last().expect("audit emits a verdict line");
    assert!(
        last.starts_with("OK: the gate is the CI gate"),
        "a complete gate must be reported clean, got:\n{text}"
    );
    assert!(!text.contains("WARN:"), "{text}");
}
